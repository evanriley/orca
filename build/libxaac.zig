//! libxaac, Ittiam's AAC decoder from AOSP, built from source for liborca.
//!
//! Only the decoder is compiled, and only its portable C paths, on every
//! target: upstream's x86 function selector, which binds each hook to a plain
//! C implementation, and the generic QMF. The per-architecture assembly is not
//! used, and the "generic" selector is not either, because it no longer
//! matches the decoder's function signatures. The file list mirrors upstream's
//! `common/common.cmake`, `decoder/libxaacdec.cmake` and
//! `decoder/drc_src/libxaacdec_drc.cmake` for the pinned release.

const std = @import("std");

pub fn addTo(b: *std.Build, module: *std.Build.Module) void {
    const libxaac = b.dependency("libxaac", .{});
    module.addIncludePath(libxaac.path("common"));
    module.addIncludePath(libxaac.path("decoder"));
    module.addIncludePath(libxaac.path("decoder/drc_src"));
    module.addCSourceFiles(.{
        .root = libxaac.path("."),
        .files = &sources,
        .flags = &.{ "-std=gnu99", "-DNDEBUG", "-DLOUDNESS_LEVELING_SUPPORT", "-fwrapv", "-w", "-fno-sanitize=undefined" },
    });
}

